import assert from "node:assert/strict";
import { signDemoSession, verifyDemoSession, DEMO_SESSION_SECONDS } from "../../src/lib/demo/session.ts";
import { consumeRateLimit } from "../../src/lib/ai/limits.ts";
import { safeNextPath } from "../../src/lib/auth/next-path.ts";
process.env.DEMO_SESSION_SECRET = "test-secret-only".repeat(4);
const now = Date.now();
const token = signDemoSession("citizen",now);
assert.equal(verifyDemoSession(token,now).role,"citizen");
assert.equal(verifyDemoSession(token,now+DEMO_SESSION_SECONDS*1000),null);
assert.equal(verifyDemoSession(token+"x",now),null);
const payload = Buffer.from(JSON.stringify({...verifyDemoSession(token,now),role:"admin"})).toString("base64url");
assert.equal(verifyDemoSession(payload+"."+token.split(".")[1],now),null);
assert.equal(verifyDemoSession("admin",now),null);
assert.equal(verifyDemoSession(token+".extra",now),null);
consumeRateLimit("test",2,100,now);consumeRateLimit("test",2,100,now);
assert.throws(()=>consumeRateLimit("test",2,100,now),/rate_limit/);
consumeRateLimit("test",2,100,now+100);
for(const value of ["@example.com","//example.com","/\\example.com","https://example.com"]) assert.equal(safeNextPath(value),null);
assert.equal(safeNextPath("/en/citizen/dashboard"),"/en/citizen/dashboard");
console.log("session-security-tests: 12 checks passed");
